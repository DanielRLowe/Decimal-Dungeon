#!/usr/bin/env python3
"""Choose one place to explore per modern campaign country from the UNESCO World Heritage List.

Defaults to the archived export. To update it, download SOURCE and supply the new path.
Only the listed name, year and public property ID are bundled. No photographs or
site descriptions are copied. Source: UNESCO World Heritage Centre, whc001.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ('https://data.unesco.org/api/explore/v2.1/catalog/datasets/whc001/exports/json'
          '?select=id_no%2Cname_en%2Ciso_codes%2Cdate_inscribed%2Ccategory%2Cdate_end')
# A few recognizable places for a young atlas reader. Every selection must appear
# in the source's own country list. For the others use an early, single-country site.
FEATURED = {
    1: 'Three ocean currents meet around these volcanic islands, about 1,000 kilometers off the South American coast.',
    63: 'Mountain gorillas live here in a park that stretches from lowland swamps to snowy mountain peaks.',
    75: 'In Arizona, the Colorado River carved through layers of rock that record two billion years of Earth’s history.',
    119: 'Students came to this city to study centuries ago, when Timbuktu was a center of learning in West Africa.',
    154: 'Along Australia’s northeast coast, corals have built reefs where dugongs and green sea turtles live.',
    156: 'Herds of wildebeest, zebras and gazelles cross these grasslands each year in search of water.',
    252: 'In the Indian city of Agra, builders used white marble to make this tomb in the 1600s.',
    274: 'The Inca built terraces and stone walls high in an Andean mountain forest, 2,430 meters above sea level.',
    303: 'On the border with Brazil, a river tumbles over a chain of waterfalls nearly three kilometers across.',
    326: 'Caravans once met in Petra, where the Nabataeans carved buildings into the rock between the Red Sea and the Dead Sea.',
    355: 'Look across these waterfalls toward Argentina. The spray helps plants grow in the forest around the falls.',
    364: 'Centuries ago the Shona people traded goods in this city, whose stone walls still stand.',
    373: 'Prehistoric builders in Wiltshire arranged enormous standing stones in circles.',
    404: 'Ancient Athenians built temples on this rocky hill above their city.',
    414: 'Northeast of Mexico City, two great pyramids in this ancient city are named for the Sun and the Moon.',
    438: 'Early builders joined separate walls together. Later generations kept extending the wall across northern China.',
    592: 'On the island of Java, square terraces give way to circular platforms as you climb this Buddhist temple.',
    668: 'Several capitals of the Khmer Empire once stood here, including the city around Angkor Wat.',
    672: 'More than a thousand limestone islands and islets rise out of the water in northeastern Vietnam.',
    715: 'Polynesian islanders carved the enormous stone figures called moai on Rapa Nui in the Pacific.',
    1252: 'Several mountain ranges meet in the Pamirs. Some peaks in the park rise above 7,000 meters.',
    1418: 'Mount Fuji is a volcano. Its snowy summit has drawn pilgrims, artists and poets for centuries.',
}


def build(export):
    nations = [json.loads(line.strip().rstrip(',')) for line in
               (ROOT / 'web/campaign-data.js').read_text().splitlines()
               if line.lstrip().startswith('{"id":')]
    records = json.loads(export.read_text())
    if len(records) < 1000:
        raise ValueError('Expected the full World Heritage List export')
    by_country = {}
    for row in records:
        if row['date_end'] or not row['iso_codes']:
            continue
        site_id = int(row['id_no'])
        year = int(row['date_inscribed'])
        priority = (site_id not in FEATURED, len(row['iso_codes']) > 1, year, len(row['name_en']), site_id)
        for iso in row['iso_codes']:
            current = by_country.get(iso)
            if current is None or priority < current[0]:
                by_country[iso] = (priority, {'id': site_id, 'name': row['name_en'].strip(), 'year': year})
    sites = {n['iso2']: by_country[n['iso2']][1] for n in nations if n['iso2'] in by_country}
    for site in sites.values():
        if site['id'] in FEATURED:
            site['fact'] = FEATURED[site['id']]
    if len(sites) < 150:
        raise ValueError('Unexpectedly low country coverage')
    output = ROOT / 'web/heritage-sites.js'
    output.write_text('/* UNESCO World Heritage Centre, whc001. Generated by build-heritage-sites.py. */\n'
                      'globalThis.DungeonHeritageSites = ' +
                      json.dumps(sites, indent=2, ensure_ascii=False, sort_keys=True) + ';\n')
    print(f'{len(sites)} countries with a featured World Heritage Site')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, epilog=SOURCE)
    parser.add_argument('export', nargs='?', type=Path, default=ROOT / 'scripts/profile-sources/unesco-heritage.json')
    build(parser.parse_args().export)
